/** 고르기 — 'all' = 전체, 's{n}' = 교재 n단계 약어 묶음, 그 밖 = 약어 하나(id) */
export type AbbrPick = string

export const PICK_ALL = 'all'
export const pickOfStage = (n: number) => `s${n}`

/** 교재 단계별 묶음 (표 순서) */
export const DRILL_GROUPS: { stage: number; drills: AbbrDrill[] }[] = [...new Set(ABBR_DRILLS.map((d) => d.stage))].map(
  (stage) => ({ stage, drills: ABBR_DRILLS.filter((d) => d.stage === stage) }),
)

export function isValidPick(p: unknown): p is AbbrPick {
  if (p === PICK_ALL) return true
  if (typeof p !== 'string') return false
  return DRILL_GROUPS.some((g) => pickOfStage(g.stage) === p) || ABBR_DRILLS.some((d) => d.id === p)
}

export function drillsFor(pick: AbbrPick): AbbrDrill[] {
  if (pick === PICK_ALL) return ABBR_DRILLS
  const g = DRILL_GROUPS.find((x) => pickOfStage(x.stage) === pick)
  if (g) return g.drills
  const one = ABBR_DRILLS.find((d) => d.id === pick)
  return one ? [one] : ABBR_DRILLS
}

export function pickLabel(pick: AbbrPick): string {
  if (pick === PICK_ALL) return '전체'
  const g = DRILL_GROUPS.find((x) => pickOfStage(x.stage) === pick)
  if (g) return `${g.stage}단계 약어`
  return ABBR_DRILLS.find((d) => d.id === pick)?.label ?? '전체'
}

/** 고른 약어의 키 — 하나일 때만 (여럿이면 강조가 뒤섞여 의미가 없다) */
export function pickKeys(pick: AbbrPick): KeyRef[] {
  const ds = drillsFor(pick)
  return ds.length === 1 ? ds[0].keys : []
}
