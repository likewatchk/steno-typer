/**
 * 소리자바 11단계 — 1~10단계 기본약어 총정리 (교재 p109~110 표).
 *
 * 표의 약어 36개 + 5단계에서 배운 '로'(표에는 빠짐) — 약어마다 그 약어가 들어간 문장 10개.
 * 약어 타법은 표 그대로이고, 1~10단계 약어 연습 힌트도 여기서 가져간다 (같은 약어 = 같은 문구).
 *
 * 1~10단계를 차례로 복습하도록:
 * - N단계 약어의 문장은 N단계까지 배운 자리만 쓴다 (약어가 찍어 주는 글자는 예외) — 테스트가 검증.
 *   그래서 앞 단계 문장은 교재 앞 단계 문장처럼 짧고 받침·모음이 단출하다.
 * - 연습 본문은 1단계 약어 → 10단계 약어 순서. 섞기는 단계 묶음 안에서만.
 * - 를(을)·와(과)·므로(으로)처럼 한 타법이 앞 글자 받침에 따라 두 꼴로 나오는 약어는 두 꼴을 섞었다.
 * - 므로서·므로써는 맞춤법상 받침 뒤 '으로서·으로써' 꼴로만 쓴다 (교재: 감으로써 O, 가므로써 X).
 * - '에게·에서'처럼 약어 둘이 붙어 타법이 모호한 꼴은 피했다.
 */
